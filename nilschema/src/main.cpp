// nilschema - Ny schema extraction tool
// Scans directories for .ny files containing @schema tags and copies them to output.

#include <iostream>
#include <fstream>
#include <sstream>
#include <string>
#include <vector>
#include <filesystem>
#include "nil_version.hpp"

namespace fs = std::filesystem;

// Check if file contains @schema tag
bool is_schema_file(const fs::path& filepath) {
    std::ifstream file(filepath);
    if (!file.is_open()) return false;

    std::string line;
    while (std::getline(file, line)) {
        // Check for @schema (with optional whitespace)
        size_t pos = line.find("@schema");
        if (pos != std::string::npos) {
            // Make sure it's not in a comment
            size_t comment_pos = line.find('#');
            if (comment_pos == std::string::npos || comment_pos > pos) {
                return true;
            }
        }
    }
    return false;
}

// Copy file preserving relative path structure
bool copy_schema(const fs::path& source_file, const fs::path& source_root, const fs::path& dest_root) {
    // Get relative path from source root
    fs::path rel_path = fs::relative(source_file, source_root);
    fs::path dest_path = dest_root / rel_path;

    // Create destination directories if needed
    fs::create_directories(dest_path.parent_path());

    // Copy the file
    try {
        fs::copy_file(source_file, dest_path, fs::copy_options::overwrite_existing);
        return true;
    } catch (const fs::filesystem_error& e) {
        std::cerr << "Error copying " << source_file << ": " << e.what() << std::endl;
        return false;
    }
}

void print_usage() {
    std::cout << "Usage: nilschema <input_dir> <output_dir>" << std::endl;
    std::cout << "       nilschema --help|--version" << std::endl;
    std::cout << std::endl;
    std::cout << "Scans input_dir for .ny files containing an @schema tag" << std::endl;
    std::cout << "and copies them to output_dir preserving directory structure." << std::endl;
    std::cout << std::endl;
    std::cout << "Example:" << std::endl;
    std::cout << "  nilschema nilstd/src/ release/include/" << std::endl;
}

int main(int argc, char* argv[]) {
    if (argc == 2 && std::string(argv[1]) == "--version") {
        std::cout << "nilschema " << NIL_VERSION << '\n';
        return 0;
    }
    if (argc == 2 && (std::string(argv[1]) == "-h" ||
                      std::string(argv[1]) == "--help")) {
        print_usage();
        return 0;
    }
    if (argc < 3) {
        print_usage();
        return 1;
    }

    fs::path input_dir = argv[1];
    fs::path output_dir = argv[2];

    if (!fs::exists(input_dir)) {
        std::cerr << "Error: Input directory does not exist: " << input_dir << std::endl;
        return 1;
    }

    if (!fs::is_directory(input_dir)) {
        std::cerr << "Error: Input path is not a directory: " << input_dir << std::endl;
        return 1;
    }

    // Create output directory if needed
    fs::create_directories(output_dir);

    std::cout << "Scanning for @schema files in: " << input_dir << std::endl;

    int total_files = 0;
    int schema_files = 0;
    std::vector<std::string> extracted;

    // Recursively scan for .ny files.
    for (const auto& entry : fs::recursive_directory_iterator(input_dir)) {
        if (!entry.is_regular_file()) continue;

        fs::path filepath = entry.path();
        std::string ext = filepath.extension().string();

        if (ext == ".ny") {
            total_files++;

            if (is_schema_file(filepath)) {
                if (copy_schema(filepath, input_dir, output_dir)) {
                    schema_files++;
                    fs::path rel = fs::relative(filepath, input_dir);
                    extracted.push_back(rel.string());
                    std::cout << "  [SCHEMA] " << rel << std::endl;
                }
            }
        }
    }

    std::cout << std::endl;
    std::cout << "Summary:" << std::endl;
    std::cout << "  Total .ny files scanned: " << total_files << std::endl;
    std::cout << "  Schema files extracted:  " << schema_files << std::endl;
    std::cout << "  Output directory: " << output_dir << std::endl;

    // Write manifest
    fs::path manifest = output_dir / "schema_manifest.txt";
    std::ofstream mf(manifest);
    if (mf.is_open()) {
        mf << "# Schema Manifest - Generated by nilschema" << std::endl;
        mf << "# " << schema_files << " schema files" << std::endl;
        for (const auto& f : extracted) {
            mf << f << std::endl;
        }
        std::cout << "  Manifest written: " << manifest << std::endl;
    }

    return 0;
}
